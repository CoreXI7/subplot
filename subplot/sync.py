#!/usr/bin/env python3
"""Subplot: the gate between incoming/ and queue/ or review/ (<prefix>-sync.service; no network, no secrets; media read-only).
ARCHITECTURE.md "sync.py". Every file in incoming/ (found by find.py or generated by gen.py) is re-validated, measured against the
speech in the video's audio (vad.py: Silero VAD over the whole track, cross-correlation on each half), and routed. ffmpeg is
the only program run (by vad.py, with an argument list, a byte cap and a timeout). A found file is kept when it is in sync,
shifted and re-measured when it is off by up to find.auto_shift_max_ms, discarded otherwise; a generated file is never
shifted (Whisper's timeline is the audio's own) and is routed by confidence; its measurement is logged as free ground truth."""
import math, os, shutil, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common as C
import vad

AUTO_SHIFT_DEFAULT_MS = 60 * 1000                       # rules.find.auto_shift_max_ms: up to this a measured offset is applied and re-checked; beyond it the file is discarded
PREVIEW_CUES = 40
VAD_OK = os.path.join(C.STATE, "vad-ok")                # exists while the speech detector loads (the board's self-check)

speech_spans = vad.speech_spans                         # tests replace these module attributes
measure_offset = vad.measure
load_detector = vad.load


def _field(obj, name, default=None):
    if isinstance(obj, dict):
        return obj.get(name, default)
    return getattr(obj, name, default)


def _number(obj, names, default):
    for name in names:
        value = _field(obj, name, None)
        if isinstance(value, (int, float)) and not isinstance(value, bool):
            return value
    return default


def shift_cues(cues, offset_ms):
    """The cues moved by offset_ms: a cue that would end at or before 0 is dropped, a start before 0 becomes 0 and keeps
    at least 1 ms of duration (no phantom 0-1 ms cues)."""
    out = []
    for a, b, t in cues:
        a, b = a + offset_ms, b + offset_ms
        if b <= 0:
            continue
        a = max(0, a)
        out.append((a, max(a + 1, b), t))
    return out


def apply_timing(cues, measured, spans, duration_ms, rules, regions=None):
    """The timing policy for a FOUND file (the owner's rule: a shift up to find.auto_shift_max_ms, else discard), given
    measure_offset's verdict. Returns (ok, offset_ms | None, cues, why); offset_ms is the shift APPLIED, null otherwise:
    - no agreed measurement -> (False, None, cues, "timing not confirmed (<why>)"): a timing verdict, discarded
    - |offset| <= find.sync_max_offset_ms -> (True, None, cues, "")
    - |offset| <= find.auto_shift_max_ms -> the ORIGINAL cues shifted by offset and measured AGAIN (that verdict is added
      to measured as "after_shift"); within the limit -> (True, offset, shifted, ""), else
      (False, None, cues, "off by N s; shift did not fit (...)")
    - larger -> (False, None, cues, "off by N s")."""
    find_rules = _field(rules, "find", None)
    limit = _number(find_rules, ("sync_max_offset_ms",), 500)
    auto = _number(find_rules, ("auto_shift_max_ms",), AUTO_SHIFT_DEFAULT_MS)
    offset = _field(measured, "offset_ms", None)
    if not isinstance(offset, (int, float)) or isinstance(offset, bool) or not math.isfinite(offset):
        return False, None, cues, f"timing not confirmed ({_field(measured, 'why', None) or 'no agreement'})"
    offset = int(round(offset))
    if abs(offset) <= limit:
        return True, None, cues, ""                                        # in sync: nothing applied (offset_ms stays null)
    if abs(offset) > auto:
        return False, None, cues, f"off by {offset / 1000:.1f} s"
    shifted = shift_cues(cues, offset)
    if not shifted:
        return False, None, cues, f"off by {offset / 1000:.1f} s"
    again = measure_offset(shifted, spans, duration_ms, regions)
    if isinstance(measured, dict):
        measured["after_shift"] = again                                    # the verdict on the cues as they leave
    offset2 = _field(again, "offset_ms", None)
    if isinstance(offset2, (int, float)) and not isinstance(offset2, bool) and math.isfinite(offset2) and abs(offset2) <= limit:
        return True, offset, shifted, ""
    detail = f"still off by {offset2 / 1000:.1f} s" if isinstance(offset2, (int, float)) and not isinstance(offset2, bool) and math.isfinite(offset2) \
        else (_field(again, "why", None) or "not confirmed")
    return False, None, cues, f"off by {offset / 1000:.1f} s; shift did not fit ({detail})"


def route(meta, cues, rules, es_kept):
    """'queue' | 'review' | 'discard' per ARCHITECTURE 'sync.py': step 'find' -> queue; step 'gen' -> by meta['confidence'] against
    thresholds (>= keep queue, >= review review, else discard); a generated Spanish file ('es' or 'es-419') -> review while
    es_kept < generate.es_review_until_kept."""
    if _field(meta, "step", "find") != "gen":
        return "queue"
    gen = _field(rules, "generate", None)
    if gen is None:
        gen = {}
    lang = ""
    for name in ("language", "lang", "language_detected"):
        value = _field(meta, name, None)
        if value:
            lang = str(value).lower()
            break
    keep_review_until = _number(gen, ("es_review_until_kept",), 0)
    if lang in ("es", "es-419") and (es_kept or 0) < keep_review_until:
        return "review"
    confidence = _field(meta, "confidence", 0.0)
    try:
        confidence = float(confidence)
    except (TypeError, ValueError):
        confidence = 0.0
    thresholds = _field(rules, "thresholds", None)                       # rules.thresholds.keep/review (validated by load_rules)
    keep = _number(thresholds, ("keep",), 0.85)
    review = _number(thresholds, ("review",), 0.6)
    if confidence >= keep:
        return "queue"
    if confidence >= review:
        return "review"
    return "discard"


def drop_placed(key, why):
    """A re-gated placement (repair_placed.py put our own sidecar back through the gate) was discarded: write a "delete"
    decision so <prefix>-place removes the sidecar we placed (marker + manifest must match) and clears the mark. Under the
    per-key flock the board and place share; never overwrites a decision the owner made."""
    import fcntl
    C.ensure_dir(C.DECISIONS)
    lock = os.open(os.path.join(C.DECISIONS, key + ".lock"), os.O_RDWR | os.O_CREAT | C.NOFOLLOW, 0o600)
    try:
        fcntl.flock(lock, fcntl.LOCK_EX)
        if C.decision(key) is None:
            C.write_json(os.path.join(C.DECISIONS, key + ".json"),
                         {"decision": "delete", "at": C.now(), "by": "sync", "why": f"re-gated file not confirmed: {why}"[:200]})
    finally:
        os.close(lock)


def process_one(key, lang, library, rules):
    """Gate one incoming pair. Steps: read incoming/<key>.<lang>.srt (cap) and .json; C.validate_subtitle; item =
    library['items'][key] (missing or status != 'ok' -> review 'video missing'); video = C.safe_media_path(item['path'],
    rules); speech_spans(video, duration_ms) (a SpeechError such as "ffmpeg exit N" -> review); measure_offset; a found file goes through
    apply_timing, a generated file is never shifted (its measurement is kept as 'measured'); write the final bytes with
    C.write_srt(cues, (key, meta['source'], meta['confidence'])) to the routed folder with the json beside it (adding
    'offset_ms', 'measured', 'why', and for review 'preview' = first PREVIEW_CUES cues as [[start_ms, end_ms, text], ...]);
    remove the incoming pair; on discard C.mark(key, gen_failed_inc=1) when step is 'gen'; C.done({...}) for every outcome
    with result queued | review | discarded | rejected. Returns the route string."""
    srt_name = f"{key}.{lang}.srt"
    srt_in = os.path.join(C.INCOMING, srt_name)
    json_in = os.path.join(C.INCOMING, f"{key}.{lang}.json")
    raw = C.read_bytes(srt_in, C.MAX_SUB_BYTES)
    meta = C.read_json(json_in, 64 * 1024)
    bad_meta = (not isinstance(meta, dict) or meta.get("step") not in ("find", "gen")
                or not isinstance(meta.get("confidence"), (int, float)) or isinstance(meta.get("confidence"), bool))
    if not bad_meta:
        c = meta.get("confidence", 0)
        bad_meta = isinstance(c, bool) or not isinstance(c, (int, float)) or not math.isfinite(c)
    if not isinstance(meta, dict):
        meta = {}
    meta.setdefault("step", "find")
    meta.setdefault("confidence", 0.0)
    if not meta.get("source"):
        meta["source"] = meta["step"]
    step = meta["step"]
    items = (library or {}).get("items", {}) if isinstance(library, dict) else {}
    item = items.get(key)
    cues = None
    why = ""
    measured = None
    if raw is not None:
        try:
            cues, why = C.validate_subtitle(raw, lang)
        except C.SubtitleError:
            cues, why = None, "invalid subtitle"

    def finish(result, why_text, offset=None, folder=None):
        if result == "review" and str(why_text).startswith("off by") and meta.get("shifted_by"):
            why_text = f"{why_text} (after a {int(meta['shifted_by']) / 1000:.1f} s fix; a single shift does not fit this file)"
        if folder is not None:
            C.ensure_dir(folder)
            marker = (key, meta.get("source"), meta.get("confidence", 0.7))
            data = C.write_srt(cues, marker)
            if isinstance(data, str):
                data = data.encode("utf-8")
            C.write_bytes(os.path.join(folder, srt_name), data)
            out_meta = dict(meta)
            out_meta["offset_ms"] = offset
            if measured is not None:
                out_meta["measured"] = measured
            out_meta["why"] = why_text
            if result == "review" and cues is not None:
                out_meta["preview"] = [[start, end, text] for start, end, text in cues[:PREVIEW_CUES]]
            C.write_json(os.path.join(folder, f"{key}.{lang}.json"), out_meta)
        for path in (srt_in, json_in):
            try:
                os.unlink(path)
            except OSError:
                pass
        entry = {"step": "sync", "key": key, "lang": lang, "result": result, "why": why_text,
                 "source": meta.get("source"), "confidence": meta.get("confidence")}
        if measured is not None:
            entry["measured_ms"] = measured.get("offset_ms")
        if isinstance(item, dict):
            for name in ("show", "title", "season", "episode", "library"):
                if item.get(name) is not None:
                    entry[name] = item[name]
        C.done(entry)

    if cues is None or bad_meta:
        finish("rejected", "metadata missing" if bad_meta else (why or "invalid subtitle"))
        return "discard"
    if not isinstance(item, dict) or item.get("status") != "ok":
        finish("review", "video missing", folder=C.REVIEW)
        return "review"
    video = None
    try:
        video = C.safe_media_path(item.get("path", ""), rules)
    except (C.SubtitleError, TypeError, ValueError, OSError):
        video = None
    if not video:
        finish("review", "video missing", folder=C.REVIEW)
        return "review"

    offset = None
    sync_ok, sync_why = True, ""
    try:
        known = item.get("duration_ms")
        spans, duration_ms, regions = speech_spans(video, known if isinstance(known, int) and not isinstance(known, bool) and known > 0 else None)
    except vad.SpeechError as exc:
        sync_ok, sync_why = False, str(exc) or "sync failed"
    else:
        measured = measure_offset(cues, spans, duration_ms, regions)
        if not isinstance(measured, dict):
            measured = {"offset_ms": None, "why": "no peak"}
        else:
            measured["regions"] = [list(r) for r in regions]
        if step != "gen":                                                 # a generated file keeps Whisper's own timeline
            sync_ok, offset, cues, sync_why = apply_timing(cues, measured, spans, duration_ms, rules, regions)
    es_doc = C.read_json(C.ES_KEPT, 4096)
    es_kept = _number(es_doc if isinstance(es_doc, dict) else {}, ("kept",), 0)
    route_meta = dict(meta)
    route_meta["language"] = lang
    routed = route(route_meta, cues, rules, es_kept)
    if not sync_ok:
        # a timing verdict is final: the file is for another cut (or its timing cannot be confirmed) and Whisper will make
        # a fitting one; other failures (ffmpeg, a missing video) still go to the owner
        timing = str(sync_why).startswith(("off by", "timing not confirmed"))
        owner_asked = bool(meta.get("shifted_by"))                     # a Fix-timing file that still misses: the owner hears why
        routed, why = ("discard" if timing and not owner_asked else "review"), sync_why or "sync failed"
    elif routed == "review" and step == "gen":
        keep = _number(_field(rules, "thresholds", None), ("keep",), 0.85)
        why = f"confidence {float(meta.get('confidence') or 0):.2f} is below keep {keep:.2f}"   # the card says why it waits
    else:
        why = ""
    if routed == "discard":
        if step == "gen":
            C.mark(key, gen_failed_inc=1)
        if meta.get("regated") and step != "gen":
            drop_placed(key, why)                                         # the old sidecar of a re-gated file must not stay
        finish("discarded", why)
        return "discard"
    if routed == "queue":
        finish("queued", why, offset=offset, folder=C.QUEUE)
        return "queue"
    finish("review", why, offset=offset, folder=C.REVIEW)
    return "review"


def main():
    rules = C.load_rules()
    if rules is None:
        C.log("no valid rules; nothing synced")
        return 0
    try:
        names = sorted(n for n in os.listdir(C.INCOMING) if n.endswith(".srt"))
    except OSError:
        names = []
    try:
        load_detector()                                                   # every run, so vad-ok never goes stale
    except vad.Unavailable as exc:
        try:
            os.unlink(VAD_OK)
        except OSError:
            pass
        if names:
            C.log(f"speech detector unavailable ({exc}); {len(names)} incoming file(s) left for a later run")
        return 0
    try:
        C.write_bytes(VAD_OK, b"")
    except OSError:
        pass
    if not names:
        return 0
    library = C.read_json(C.LIBRARY, 200 * 1024 * 1024) or {"items": {}}
    for name in names:
        stem = name[:-4]
        key, _, lang = stem.rpartition(".")
        if not C.ITEM_KEY.fullmatch(key) or not C.LANG.fullmatch(lang):
            C.log(f"incoming: odd name ignored")
            continue
        try:
            process_one(key, lang, library, rules)
        except Exception as exc:                                  # one bad file never stops the others
            C.log(f"sync {key} {lang}: {type(exc).__name__}: {exc}")
            C.done({"step": "sync", "key": key, "lang": lang, "result": "failed", "why": f"sync crashed: {type(exc).__name__}"})
    return 0


if __name__ == "__main__":
    sys.exit(main())
